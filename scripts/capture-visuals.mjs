import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const siteUrl = 'https://folio.3303147509.workers.dev/';
const outputDir = process.env.SNAPSHOT_DIR ?? '/tmp/folio-visual-snapshots';
const sourceCommit = process.env.SOURCE_COMMIT ?? 'unknown';
const sections = [
  ['scripts', '剧本'],
  ['images', '影像'],
  ['inspiration', '灵感'],
  ['about', '关于'],
];

await mkdir(outputDir, { recursive: true });
const browser = await chromium.launch({ headless: true });

async function capture(page, name) {
  const screenshot = await page.screenshot({
    type: 'jpeg',
    quality: 70,
    fullPage: true,
    animations: 'disabled',
  });
  // GitHub connector text-file access works for ASCII snapshots, not binary downloads.
  await writeFile(path.join(outputDir, `${name}.b64`), screenshot.toString('base64') + '\n', 'utf8');
  console.log(`Captured ${name}: ${screenshot.byteLength} bytes`);
}

try {
  for (const [device, width, height] of [
    ['desktop', 1440, 900],
    ['mobile', 390, 844],
  ]) {
    const page = await browser.newPage({
      viewport: { width, height },
      deviceScaleFactor: 1,
      locale: 'zh-CN',
    });
    await page.goto(siteUrl, { waitUntil: 'networkidle', timeout: 60000 });
    await page.evaluate(() => document.fonts.ready);
    await capture(page, `${device}-00-welcome`);

    await page.getByRole('button', { name: '进入', exact: true }).click();
    await capture(page, `${device}-01-home`);

    for (const [sectionId, label] of sections) {
      await page.locator('.side-dock button').filter({ hasText: label }).first()
        .evaluate((button) => button.click());
      await capture(page, `${device}-${sectionId}`);

      if (sectionId === 'scripts') {
        await page.locator('.script-book').first().evaluate((button) => button.click());
        await capture(page, `${device}-scripts-dialog`);
        await page.locator('.dialog-close').evaluate((button) => button.click());
      }
    }
    await page.close();
  }

  const names = [
    '00-welcome', '01-home', 'scripts', 'scripts-dialog', 'images', 'inspiration', 'about',
  ];
  const manifest = [
    '# Visual snapshots',
    '',
    `- Live URL: ${siteUrl}`,
    `- Source commit: \`${sourceCommit}\``,
    `- Captured (UTC): ${new Date().toISOString()}`,
    '- Generated by: GitHub Actions + Playwright',
    '- Format: UTF-8 Base64-encoded JPEG (decode before image viewing)',
    '',
    '## Files',
    ...['desktop', 'mobile'].flatMap((device) => names.map((name) => `- \`${device}-${name}.b64\``)),
    '',
  ].join('\n');
  await writeFile(path.join(outputDir, 'manifest.md'), manifest, 'utf8');
} finally {
  await browser.close();
}
